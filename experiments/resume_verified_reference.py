"""Resume one interrupted benchmark pair using an independently rerun R fit.

This execution workaround changes no model, optimizer, split or test selection.
The independent R invocation must use the saved prepared CSVs. Its input and
script hashes are verified again against the data regenerated by the suite.
"""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
import argparse
import hashlib
import json
import subprocess
import numpy as np
import experiments.run_manuscript_benchmarks as benchmark


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--dataset',required=True)
    ap.add_argument('--regime',choices=['A','B'],required=True)
    ap.add_argument('--split-seed',type=int,required=True)
    ap.add_argument('--output',type=Path,required=True)
    args=ap.parse_args()
    cfg=next(c for c in benchmark.DATASETS if c['name']==args.dataset)
    payload=json.loads(args.output.read_text())
    assert payload['protocol']['epochs']==2000
    if any(r['dataset']==args.dataset and r['regime']==args.regime for r in payload['results']):
        raise ValueError('Requested pair is already complete')
    work=benchmark.DATA_DIR/'manuscript_runs'/f"{cfg['loader']}_{args.regime}_2000_split{args.split_seed}"/'mixed'
    df=benchmark.load(cfg['loader'])
    tr,te=(benchmark.within_group_holdout(df,cfg['group'],seed=args.split_seed) if args.regime=='A'
           else benchmark.group_holdout(df,cfg['group'],seed=args.split_seed))
    train,query,_,formula,*_=benchmark.prepare(cfg,df,tr,te)
    expected={name:digest(frame.to_csv(index=False).encode()) for name,frame in
              [('train',train),('query',query.drop(columns='y'))]}
    for name,sha in expected.items():
        assert digest((work/f'{name}.csv').read_bytes())==sha
    # Run the exact original R command before initializing the training runtime.
    result_path=work/'independent_reference.json'
    cmd=['Rscript',str(ROOT/'experiments/mixed_reference.R'),str(work/'train.csv'),
         str(work/'query.csv'),formula,cfg['task'],args.regime,str(result_path)]
    subprocess.run(cmd,check=True)
    reference=json.loads(result_path.read_text())
    if not reference['converged']: raise RuntimeError('Independent reference did not converge')
    provenance=dict(reason='pwrssUpdate failure in combined runner; independent exact-command fit replayed',
        input_sha256=expected,reference_sha256=digest(result_path.read_bytes()),
        R_script_sha256=digest((ROOT/'experiments/mixed_reference.R').read_bytes()),
        runner_sha256=digest(Path(__file__).read_bytes()))
    original=benchmark.classical
    def replay(train,query,formula_arg,task,regime,work_arg):
        if work_arg!=work: return original(train,query,formula_arg,task,regime,work_arg)
        assert formula_arg==formula and task==cfg['task'] and regime==args.regime
        assert digest(train.to_csv(index=False).encode())==expected['train']
        assert digest(query.drop(columns='y').to_csv(index=False).encode())==expected['query']
        ref=dict(reference); pred=np.asarray(ref.pop('prediction'))
        ref['independent_replay']=provenance
        return pred,ref
    benchmark.classical=replay
    sys.argv=['run_manuscript_benchmarks.py','--datasets',args.dataset,'--regimes',args.regime,
              '--split-seed',str(args.split_seed),'--output',str(args.output),'--resume']
    benchmark.main()

if __name__=='__main__': main()
